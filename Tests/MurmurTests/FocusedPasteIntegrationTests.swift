import AppKit
import Carbon.HIToolbox
import MurmurCore
import Testing
@testable import Murmur

/// The real delivery path — `TargetedDelivery` + `TargetGuard` + `ClipboardPaster` with a real
/// `NSPasteboard` — against this test's own off-screen window. Nothing here touches the user's
/// clipboard (a private named pasteboard) or other apps (key events are captured, not posted;
/// "which app is frontmost" is simulated because activating the test runner would steal focus).
/// A captured ⌘V behaves like AppKit's paste: the focused field reads the pasteboard.
@MainActor
@Suite("Focused paste — own window, private pasteboard", .serialized)
final class FocusedPasteIntegrationTests {
    private static let ownPID = ProcessInfo.processInfo.processIdentifier
    private static let ownBundle = Bundle.main.bundleIdentifier
    private static let userClipboard = "the user's clipboard"
    private static let userRichType = NSPasteboard.PasteboardType("app.hushy.tests.rich")

    private let window: NSWindow
    private let mailField = NSTextField(frame: NSRect(x: 10, y: 90, width: 280, height: 24))
    private let chatField = NSTextField(frame: NSRect(x: 10, y: 50, width: 280, height: 24))
    private let passwordField = NSSecureTextField(frame: NSRect(x: 10, y: 10, width: 280, height: 24))
    private let pasteboard = NSPasteboard(name: NSPasteboard.Name("app.hushy.tests.\(UUID().uuidString)"))
    private let reader: WindowFocusReader
    private var paster: ClipboardPaster!
    private var keys: [String] = []
    /// Runs right after a captured ⌘V (i.e. during the pre-Return wait).
    private var afterPasteKey: () -> Void = {}
    /// False makes the captured ⌘V fail to post (CGEvent couldn't be created).
    private var pasteKeyPosts = true

    init() {
        _ = NSApplication.shared
        window = NSWindow(contentRect: NSRect(x: 0, y: 0, width: 300, height: 130),
                          styleMask: [.titled], backing: .buffered, defer: true)
        window.isReleasedWhenClosed = false
        for field in [mailField, chatField, passwordField] { window.contentView?.addSubview(field) }
        reader = WindowFocusReader(window: window, ownPID: Self.ownPID, ownBundle: Self.ownBundle)
        paster = ClipboardPaster(pasteboard: pasteboard, postKey: { [unowned self] key, flags in
            self.capture(key: key, flags: flags)
        }, restoreDelay: .milliseconds(20), returnDelay: .milliseconds(5))
        let item = NSPasteboardItem()
        item.setString(Self.userClipboard, forType: .string)
        item.setData(Data([1, 2, 3]), forType: Self.userRichType)
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
    }

    isolated deinit {
        pasteboard.releaseGlobally()
    }

    /// AppKit's paste, minus the event system: the focused field of the frontmost app reads the
    /// pasteboard. A ⌘V that would reach another app is recorded as such.
    private func capture(key: CGKeyCode, flags: CGEventFlags) -> Bool {
        if key == CGKeyCode(kVK_ANSI_V), flags.contains(.maskCommand) {
            guard pasteKeyPosts else { return false }
            keys.append("⌘V")
            if reader.isOwnAppFrontmost, let field = reader.currentField as? NSTextField {
                field.stringValue += pasteboard.string(forType: .string) ?? ""
            } else {
                keys.append("⌘V-into-another-app")
            }
            afterPasteKey()
        } else if key == CGKeyCode(kVK_Return) {
            keys.append("↩")
        }
        return true
    }

    /// Key-down: focus the mail field and bind to it.
    private func bindToMail() -> BoundFocus<NSView> {
        #expect(window.makeFirstResponder(mailField))
        let pid = reader.frontmostApp()?.processID
        let field = pid.flatMap(reader.focusedField)
        return BoundFocus(processID: pid, bundleID: reader.frontmostApp()?.bundleID,
                          field: field, window: pid.flatMap(reader.focusedWindow),
                          fieldIsSecure: field.map { reader.security($0) == .secure } ?? false)
    }

    private func deliver(
        _ text: String, to bound: BoundFocus<NSView>, pressReturn: Bool = false, hasTextInput: Bool = true,
        noFieldClipboard: NoFieldClipboardPolicy = .current
    ) async -> DeliveryResult {
        let reader = reader
        let result = await TargetedDelivery.deliver(
            text: text, pressReturn: pressReturn, hasTextInput: hasTextInput,
            check: { TargetGuard.check(bound, reader: reader) }, noFieldClipboard: noFieldClipboard, paster: paster)
        await paster.waitForPendingRestore()
        return result
    }

    /// Marked for clipboard-history managers to skip (`org.nspasteboard.TransientType` +
    /// `AutoGeneratedType`), as every clipboard write Hushy makes on its own is.
    private var isMarkedTransient: Bool {
        pasteboard.data(forType: ClipboardPaster.transientType) != nil
            && pasteboard.data(forType: ClipboardPaster.autoGeneratedType) != nil
    }

    private var clipboardIsTheUsers: Bool {
        pasteboard.string(forType: .string) == Self.userClipboard
            && pasteboard.data(forType: Self.userRichType) == Data([1, 2, 3])
    }

    @Test("same field: pasted into it, Return sent, and every clipboard type restored")
    func pastesIntoBoundField() async {
        let bound = bindToMail()
        let result = await deliver("Ship it Thursday.", to: bound, pressReturn: true)
        #expect(result == .pasted)
        #expect(mailField.stringValue == "Ship it Thursday.")
        #expect(keys == ["⌘V", "↩"])
        #expect(clipboardIsTheUsers)
    }

    @Test("clicked another field in the same app: nothing pasted, text left for ⌘V")
    func anotherFieldCopies() async {
        let bound = bindToMail()
        window.makeFirstResponder(chatField)
        let result = await deliver("Ship it Thursday.", to: bound, pressReturn: true)
        #expect(result == .copied(.field))
        #expect(keys.isEmpty)
        #expect(mailField.stringValue.isEmpty && chatField.stringValue.isEmpty)
        #expect(pasteboard.string(forType: .string) == "Ship it Thursday.")
        #expect(isMarkedTransient, "Hushy's own copy: clipboard-history managers skip it, ⌘V still works")
    }

    @Test("switched apps: nothing pasted anywhere, text left for ⌘V")
    func switchedAppsCopies() async {
        let bound = bindToMail()
        reader.simulatedFrontmost = (processID: 99_999, bundleID: "com.example.chat")
        let result = await deliver("Ship it Thursday.", to: bound)
        #expect(result == .copied(.app))
        #expect(keys.isEmpty)
        #expect(pasteboard.string(forType: .string) == "Ship it Thursday.")
    }

    @Test("the original field was closed: copied with the field-closed reason")
    func closedFieldCopies() async {
        let bound = bindToMail()
        mailField.removeFromSuperview()
        window.makeFirstResponder(chatField)
        let result = await deliver("Ship it Thursday.", to: bound)
        #expect(result == .copied(.fieldClosed))
        #expect(keys.isEmpty)
    }

    @Test("moved to a password field: nothing pasted and the user's clipboard untouched")
    func passwordFieldHeld() async {
        let bound = bindToMail()
        window.makeFirstResponder(passwordField)
        let result = await deliver("Ship it Thursday.", to: bound, pressReturn: true)
        #expect(result == .heldForSecureField(.field))
        #expect(keys.isEmpty)
        #expect(passwordField.stringValue.isEmpty)
        #expect(clipboardIsTheUsers)
    }

    @Test("focus moved during the pre-Return wait: pasted, Return withheld, clipboard restored")
    func focusMovedBeforeReturn() async {
        let bound = bindToMail()
        afterPasteKey = { [window, chatField] in window.makeFirstResponder(chatField) }
        let result = await deliver("Ship it Thursday.", to: bound, pressReturn: true)
        #expect(result == .pastedReturnSkipped(.field))
        #expect(mailField.stringValue == "Ship it Thursday.")
        #expect(keys == ["⌘V"])
        #expect(clipboardIsTheUsers)
    }

    @Test("no text field at key-down: by default nothing is pasted or sent, the text is left on the clipboard")
    func noFieldCopiesByDefault() async {
        let bound = bindToMail()
        let result = await deliver("Ship it Thursday.", to: bound, pressReturn: true, hasTextInput: false)
        #expect(result == .noField(copied: true))
        #expect(keys.isEmpty)
        #expect(mailField.stringValue.isEmpty)
        #expect(pasteboard.string(forType: .string) == "Ship it Thursday.")
        #expect(isMarkedTransient)
    }

    @Test("no text field at key-down with leave-clipboard-alone: nothing pasted, sent or copied")
    func noFieldLeavesClipboardAlone() async {
        let bound = bindToMail()
        let result = await deliver(
            "Ship it Thursday.", to: bound, pressReturn: true, hasTextInput: false, noFieldClipboard: .leaveClipboardAlone)
        #expect(result == .noField(copied: false))
        #expect(keys.isEmpty)
        #expect(mailField.stringValue.isEmpty)
        #expect(clipboardIsTheUsers)
    }

    @Test("no text field at key-down with copy-automatically: text left for ⌘V as a real copy")
    func noFieldCopies() async {
        let bound = bindToMail()
        let result = await deliver(
            "Ship it Thursday.", to: bound, pressReturn: true, hasTextInput: false, noFieldClipboard: .copyAutomatically)
        #expect(result == .noField(copied: true))
        #expect(keys.isEmpty)
        #expect(mailField.stringValue.isEmpty)
        #expect(pasteboard.string(forType: .string) == "Ship it Thursday.")
        #expect(isMarkedTransient, "Hushy's own copy: clipboard-history managers skip it, ⌘V still works")
    }

    @Test("no text field and a password field focused by release: held, the user's clipboard untouched")
    func noFieldPasswordHeld() async {
        let bound = bindToMail()
        window.makeFirstResponder(passwordField)
        let result = await deliver("hunter2", to: bound, hasTextInput: false)
        #expect(result == .heldForSecureField(.field))
        #expect(keys.isEmpty)
        #expect(passwordField.stringValue.isEmpty)
        #expect(clipboardIsTheUsers)
    }

    @Test("⌘V couldn't be posted: nothing pasted, the staged text stays for ⌘V instead of being restored away")
    func failedPasteCopies() async {
        let bound = bindToMail()
        pasteKeyPosts = false
        let result = await deliver("Ship it Thursday.", to: bound, pressReturn: true)
        #expect(result == .dispatchFailed(copied: true))
        #expect(keys.isEmpty, "no ⌘V landed and no Return was sent")
        #expect(mailField.stringValue.isEmpty)
        #expect(pasteboard.string(forType: .string) == "Ship it Thursday.")
        #expect(isMarkedTransient, "Hushy's own copy: clipboard-history managers skip it, ⌘V still works")
    }

    @Test("a copy after an earlier paste isn't overwritten by that paste's pending restore")
    func copyWinsOverPendingRestore() async {
        let bound = bindToMail()
        _ = await TargetedDelivery.deliver(
            text: "First.", pressReturn: false, hasTextInput: true,
            check: { [reader] in TargetGuard.check(bound, reader: reader) }, paster: paster)
        window.makeFirstResponder(chatField) // restore of "First." still pending
        let result = await deliver("Second.", to: bound)
        #expect(result == .copied(.field))
        #expect(pasteboard.string(forType: .string) == "Second.")
    }

    // MARK: Keep dictations on the clipboard (setting, default OFF in the app)

    @Test("keep ON: a pasted dictation stays on the clipboard, marked for history managers to skip")
    func keepAfterPaste() async {
        paster.keepsPastedText = true
        let bound = bindToMail()
        let result = await deliver("Ship it Thursday.", to: bound, pressReturn: true)
        #expect(result == .pasted)
        #expect(mailField.stringValue == "Ship it Thursday.")
        #expect(keys == ["⌘V", "↩"])
        #expect(pasteboard.string(forType: .string) == "Ship it Thursday.", "not restored away")
        #expect(isMarkedTransient)
    }

    @Test("keep OFF: today's behaviour — the user's clipboard is restored after the paste")
    func keepOffRestores() async {
        paster.keepsPastedText = false
        let bound = bindToMail()
        let result = await deliver("Ship it Thursday.", to: bound)
        #expect(result == .pasted)
        #expect(clipboardIsTheUsers)
    }

    @Test("keep ON never applies to a password field: nothing pasted, the user's clipboard untouched")
    func keepNeverForSecureField() async {
        paster.keepsPastedText = true
        let bound = bindToMail()
        window.makeFirstResponder(passwordField)
        let result = await deliver("hunter2", to: bound, pressReturn: true)
        #expect(result == .heldForSecureField(.field))
        #expect(passwordField.stringValue.isEmpty)
        #expect(clipboardIsTheUsers)
    }

    @Test("keep ON: a cancelled dictation never touches the clipboard")
    func keepNeverForCancelled() async {
        paster.keepsPastedText = true
        let bound = bindToMail()
        // Cancel a child task running the delivery, not this test's own task: cancelling
        // here used to cancel the test itself, which swift-testing reports as cancelled
        // (not passed) and the expectations below never ran.
        let delivery = Task { await deliver("Ship it Thursday.", to: bound) }
        delivery.cancel()
        let result = await delivery.value
        #expect(result == .cancelled)
        #expect(keys.isEmpty)
        #expect(clipboardIsTheUsers)
    }

    @Test("keep ON: a ⌘V that couldn't be posted still copies (marked), never a half-kept paste")
    func keepWithFailedPaste() async {
        paster.keepsPastedText = true
        pasteKeyPosts = false
        let bound = bindToMail()
        let result = await deliver("Ship it Thursday.", to: bound)
        #expect(result == .dispatchFailed(copied: true))
        #expect(pasteboard.string(forType: .string) == "Ship it Thursday.")
        #expect(isMarkedTransient)
    }

    @Test("the held row's Copy is marked transient; History's deliberate Copy is a normal copy")
    func copyMarking() {
        paster.copy("hunter2", markTransient: true)
        #expect(pasteboard.string(forType: .string) == "hunter2")
        #expect(isMarkedTransient)
        paster.copy("From History")
        #expect(pasteboard.string(forType: .string) == "From History")
        #expect(!isMarkedTransient)
    }
}

/// `FocusReading` over this process's own window: the first responder is the focused field
/// (unwrapping AppKit's shared field editor to its text field), the window is the focused window.
@MainActor
final class WindowFocusReader: FocusReading {
    let window: NSWindow
    let ownPID: Int32
    let ownBundle: String?
    /// Set to pretend another app came to the front.
    var simulatedFrontmost: (processID: Int32, bundleID: String?)?

    init(window: NSWindow, ownPID: Int32, ownBundle: String?) {
        self.window = window
        self.ownPID = ownPID
        self.ownBundle = ownBundle
    }

    var isOwnAppFrontmost: Bool { simulatedFrontmost == nil }

    var currentField: NSView? {
        guard let responder = window.firstResponder else { return nil }
        if let editor = responder as? NSTextView, editor.isFieldEditor {
            return editor.delegate as? NSView
        }
        return responder as? NSView
    }

    func frontmostApp() -> (processID: Int32, bundleID: String?)? {
        simulatedFrontmost ?? (ownPID, ownBundle)
    }

    func isRunning(processID: Int32) -> Bool { processID == ownPID || processID == simulatedFrontmost?.processID }
    func focusedField(processID: Int32) -> NSView? { processID == ownPID ? currentField : nil }
    func focusedWindow(processID: Int32) -> NSView? { processID == ownPID ? window.contentView : nil }
    func isAlive(_ element: NSView) -> Bool { element.window != nil }
    func security(_ element: NSView) -> FieldSecurity { element is NSSecureTextField ? .secure : .notSecure }
    func isSame(_ lhs: NSView, _ rhs: NSView) -> Bool { lhs === rhs }
}
