import AppKit
import Testing
@testable import Murmur

@Suite("Recovery key clipboard")
@MainActor
struct RecoveryKeyClipboardTests {
    private final class Board: RecoveryKeyPasteboard {
        var options: NSPasteboard.ContentsOptions?
        var objects: [any NSPasteboardWriting] = []
        var calls: [String] = []

        func prepareForNewContents(with options: NSPasteboard.ContentsOptions) -> Int {
            self.options = options
            calls.append("prepare")
            return 0
        }

        func writeObjects(_ objects: [any NSPasteboardWriting]) -> Bool {
            self.objects = objects
            calls.append("write")
            return true
        }
    }

    @Test("Copy prepares this Mac only and marks the key transient before writing")
    func copy() throws {
        let board = Board()
        RecoveryKeyClipboard.copy("invented-recovery-key", to: board)
        #expect(board.calls == ["prepare", "write"])
        #expect(board.options == .currentHostOnly)
        #expect(board.objects.count == 1)
        let item = try #require(board.objects.first as? NSPasteboardItem)
        #expect(item.string(forType: .string) == "invented-recovery-key")
        #expect(item.types.contains(NSPasteboard.PasteboardType("org.nspasteboard.TransientType")))
        #expect(item.types.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")))
    }
}
