import AppKit
import Carbon.HIToolbox
import MurmurCore
import os

/// Pastes through a pasteboard with a synthesized ⌘V, then restores the user's clipboard.
/// `TextInserter.shared` drives `NSPasteboard.general` and real key events; tests drive a private
/// named pasteboard and a fake key poster, so they never touch the user's clipboard or apps.
@MainActor
final class ClipboardPaster: DeliveryPaster {
    typealias KeyPoster = @MainActor (_ key: CGKeyCode, _ flags: CGEventFlags) -> Bool
    typealias Snapshot = ClipboardSnapshot

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    let pasteboard: NSPasteboard
    /// Delay before restoring the clipboard; long enough for slow apps to read the paste.
    let restoreDelay: Duration
    /// Delay between ⌘V and Return, so the paste lands before the send.
    let returnDelay: Duration
    private let postKey: KeyPoster
    /// The key pressed with Command to paste. The live paster reads it from the keyboard layout
    /// (`PasteKeyboard`); the default is the key at QWERTY's V position.
    private let pasteKey: @MainActor () -> CGKeyCode
    /// "Keep dictations on the clipboard" (Settings → Writing, `SettingsSync`): after a paste
    /// that actually posted ⌘V, the dictation stays on the clipboard (marked transient) instead of
    /// the user's previous clipboard coming back. Off: the restore runs as before. Never applies to
    /// held (password-field) or cancelled dictations: those never reach ⌘V, or are withdrawn after
    /// it (`LandingSettlement.withdrawn`).
    var keepsPastedText = false

    /// The user's clipboard from before a paste whose restore hasn't run yet. A quick second
    /// dictation reuses it, so we never "restore" our own transcript over the user's clipboard.
    private var clipboardLedger = ClipboardSnapshotLedger<Snapshot>()
    /// The dictation currently staged on the pasteboard (cleared once the clipboard is no longer ours),
    /// so "is this still our transient item?" can be answered by content and marker, not change count.
    private var stagedText: String?
    /// The paste whose clipboard restore has not ended yet; its one log line is written when it does.
    private var pendingRecord: ClipboardPasteRecord?
    /// The one paste whose clipboard is held as staged until its landing check ends. `landing`
    /// names that paste, so only its own `finishLanding` settles it.
    private var pendingLanding: (landing: PasteLanding, snapshot: Snapshot, changeCount: Int, generation: UInt64)?
    private static let log = Logger(subsystem: "app.hushy", category: "clipboard")
    /// Tests: receives each `clipboard` log line.
    var onLog: ((String) -> Void)?
    private var restoreTask: Task<Void, Never>?
    private var insertionGeneration: UInt64 = 0
    /// The pasteboard's change count after this paster's own last write: the staged dictation, the restore of
    /// the earlier clipboard, or a copy. A restore that finds the clipboard changed writes nothing and leaves it.
    private var lastWriteCount: Int?

    /// True while nothing but this paster has written the pasteboard since its last write. A caller that wants
    /// to put the dictation back on the clipboard late (the second look at a paste) asks first, so it never
    /// overwrites something the person copied in between.
    var isAsLastWritten: Bool { lastWriteCount == pasteboard.changeCount }

    init(pasteboard: NSPasteboard, postKey: @escaping KeyPoster,
         restoreDelay: Duration = .milliseconds(350), returnDelay: Duration = .milliseconds(60),
         pasteKey: @escaping @MainActor () -> CGKeyCode = { CGKeyCode(kVK_ANSI_V) }) {
        self.pasteboard = pasteboard
        self.postKey = postKey
        self.pasteKey = pasteKey
        self.restoreDelay = restoreDelay
        self.returnDelay = returnDelay
    }

    /// Pastes `text` and returns as soon as ⌘V is sent; the clipboard is restored in the background.
    /// With `awaitLanding` the restore is held instead, until `finishLanding` names the same paste.
    func paste(_ text: String, pressReturn: Bool, awaitLanding: PasteLanding?,
               hasFocus: @escaping () -> Bool) async -> BoundDelivery.Outcome {
        guard !Task.isCancelled, hasFocus() else { return .focusChanged }
        let pasteboard = pasteboard
        var origin = ClipboardPasteRecord.Origin.reused
        let original = clipboardLedger.original(
            currentChangeCount: pasteboard.changeCount, isStillOurs: { self.holdsStagedText() }
        ) {
            origin = .snapshotted
            return ClipboardSnapshot.capture(pasteboard)
        }
        let record = ClipboardPasteRecord(origin: origin, saved: original)
        var staged = false
        let previousGeneration = insertionGeneration
        var generation: UInt64?
        var ourChange = -1
        let outcome = await BoundDelivery.perform(
            pressReturn: pressReturn,
            isCurrent: {
                guard !Task.isCancelled else { return false }
                return generation.map { $0 == self.insertionGeneration } ?? (previousGeneration == self.insertionGeneration)
            },
            hasFocus: hasFocus,
            prepareClipboard: {
                guard !Task.isCancelled, previousGeneration == self.insertionGeneration, hasFocus() else { return false }
                self.insertionGeneration &+= 1
                generation = self.insertionGeneration
                self.restoreTask?.cancel()
                self.finishRecord(.handedToNextPaste)
                self.pendingLanding = nil
                staged = true
                self.pendingRecord = record
                self.stagedText = text
                pasteboard.clearContents()
                guard pasteboard.writeObjects([Self.transientItem(text)]) else {
                    ourChange = pasteboard.changeCount
                    self.lastWriteCount = ourChange
                    self.restoreIfOwned(original, changeCount: ourChange, generation: self.insertionGeneration)
                    return false
                }
                ourChange = pasteboard.changeCount
                self.lastWriteCount = ourChange
                self.clipboardLedger.record(original, at: ourChange)
                if let awaitLanding {
                    self.pendingLanding = (awaitLanding, original, ourChange, self.insertionGeneration)
                } else {
                    self.scheduleClipboardRestore(original, changeCount: ourChange, generation: self.insertionGeneration)
                }
                return true
            },
            clipboardIsOwned: {
                guard let generation else { return false }
                return generation == self.insertionGeneration && ourChange >= 0
                    && (pasteboard.changeCount == ourChange || self.holdsStagedText())
            },
            paste: {
                let posted = self.postKey(self.pasteKey(), .maskCommand)
                if posted, self.keepsPastedText, awaitLanding == nil, let generation {
                    self.keepPastedText(generation: generation)
                }
                return posted
            },
            waitBeforeReturn: { try? await Task.sleep(for: self.returnDelay) },
            sendReturn: { self.postKey(CGKeyCode(kVK_Return), []) })
        if !staged { emit(record.line(.notStaged)) }
        // Nothing to wait for: ⌘V did not go out, so this paste's own held clipboard is restored.
        if let awaitLanding, outcome != .pasted, let pendingLanding, pendingLanding.landing == awaitLanding {
            self.pendingLanding = nil
            scheduleClipboardRestore(pendingLanding.snapshot, changeCount: pendingLanding.changeCount,
                                     generation: pendingLanding.generation)
        }
        return outcome
    }

    /// Ends the hold on the paste named by `landing`. A call for any other paste does nothing: once
    /// a newer paste or copy has taken the clipboard, the older paste has nothing left to settle
    /// (the newer paste carries the person's earlier clipboard and restores it itself).
    func finishLanding(_ landing: PasteLanding, as settlement: LandingSettlement) {
        guard let pending = pendingLanding, pending.landing == landing,
              pending.generation == insertionGeneration else { return }
        pendingLanding = nil
        switch settlement {
        case .confirmed where keepsPastedText:
            keepPastedText(generation: pending.generation)
        case .confirmed, .withdrawn:
            scheduleClipboardRestore(pending.snapshot, changeCount: pending.changeCount, generation: pending.generation)
        case .unconfirmed:
            // The staged item is the manual copy: nothing is written. If the person copied
            // something else meanwhile, that is theirs and stays.
            let stillStaged = pasteboard.changeCount == pending.changeCount || holdsStagedText()
            finishRecord(stillStaged ? .keptUnconfirmed : .skippedClipboardChanged)
            stagedText = nil
            clipboardLedger.clear()
        }
    }

    /// Sends Return alone to the bound target, for a command-only result ("press enter" with no
    /// other words). No clipboard is touched, so a rapid second dictation never fights this one.
    func sendReturn(hasFocus: @escaping () -> Bool) async -> BoundDelivery.Outcome {
        guard !Task.isCancelled, hasFocus() else { return .focusChanged }
        return await BoundDelivery.performReturnOnly(
            isCurrent: { !Task.isCancelled },
            hasFocus: hasFocus,
            waitBeforeReturn: { try? await Task.sleep(for: self.returnDelay) },
            sendReturn: { self.postKey(CGKeyCode(kVK_Return), []) })
    }

    /// Nothing was pasted (focus moved, no field, ⌘V failed): leave the text on the clipboard for
    /// ⌘V. The user's previous clipboard is replaced (the pill says "Copied"), an earlier paste's
    /// pending restore is cancelled so it can't overwrite this, and — like every clipboard write
    /// Hushy makes on its own — it is marked for clipboard-history managers to skip.
    func copyForManualPaste(_ text: String) {
        copy(text, markTransient: true)
    }

    /// A copy that is never restored. History's Copy is a normal copy the user asked for;
    /// `markTransient` (Hushy's own copies, the held row's Copy) adds
    /// `org.nspasteboard.TransientType` + `AutoGeneratedType` so history managers skip it.
    func copy(_ text: String, markTransient: Bool = false) {
        insertionGeneration &+= 1
        restoreTask?.cancel()
        restoreTask = nil
        finishRecord(.replacedByCopy)
        pendingLanding = nil
        stagedText = nil
        clipboardLedger.clear()
        pasteboard.clearContents()
        if markTransient {
            pasteboard.writeObjects([Self.transientItem(text)])
        } else {
            pasteboard.setString(text, forType: .string)
        }
        lastWriteCount = pasteboard.changeCount
    }

    /// The pasted dictation stays: cancel this paste's pending restore. The staged item already
    /// carries the transient markers.
    private func keepPastedText(generation: UInt64) {
        guard generation == insertionGeneration else { return }
        restoreTask?.cancel()
        restoreTask = nil
        finishRecord(.keptBySetting)
        stagedText = nil
        clipboardLedger.clear()
    }

    static func transientItem(_ text: String) -> NSPasteboardItem {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Ask clipboard managers not to record Hushy's own writes.
        item.setString("", forType: transientType)
        item.setString("", forType: autoGeneratedType)
        return item
    }

    /// Tests: waits for a scheduled clipboard restore (if any) to finish or be cancelled.
    func waitForPendingRestore() async {
        await restoreTask?.value
    }

    private func scheduleClipboardRestore(_ original: Snapshot, changeCount: Int, generation: UInt64) {
        restoreTask = Task {
            try? await Task.sleep(for: restoreDelay)
            guard !Task.isCancelled, generation == insertionGeneration else { return }
            // Only restore if nothing else touched the clipboard meanwhile.
            restoreIfOwned(original, changeCount: changeCount, generation: generation)
        }
    }

    /// Restores the user's clipboard while the pasteboard still holds our staged dictation: the same
    /// change count, or our own dictation text (a single plain-string item) that something else merely
    /// re-wrote, which bumps the count without changing what is there. Anything else on the
    /// clipboard is the person's newer copy and is left alone.
    private func restoreIfOwned(_ original: Snapshot, changeCount: Int, generation: UInt64) {
        guard generation == insertionGeneration else { return }
        let ending: ClipboardPasteRecord.Ending
        if pasteboard.changeCount == changeCount || holdsStagedText() {
            if original.restore(to: pasteboard) {
                ending = .restored
                clipboardLedger.clear(ifChangeCount: changeCount)
            } else {
                // The original is still owed: the next paste reuses it rather than saving our own text.
                ending = .failedToWrite
                clipboardLedger.record(original, at: pasteboard.changeCount)
            }
            lastWriteCount = pasteboard.changeCount
        } else {
            ending = .skippedClipboardChanged
            clipboardLedger.clear(ifChangeCount: changeCount)
        }
        stagedText = nil
        finishRecord(ending)
    }

    /// True while the pasteboard holds our staged dictation: a single item whose plain string is
    /// exactly the dictation. Decided by content, never by change count, and not by our marker
    /// either: something that re-publishes the text (a clipboard manager, Universal Clipboard) may
    /// drop the marker types. Only true while a restore is pending, i.e. within the restore window,
    /// where nobody copies text identical to the dictation by hand.
    private func holdsStagedText() -> Bool {
        guard let stagedText, let items = pasteboard.pasteboardItems, items.count == 1, let item = items.first else {
            return false
        }
        return item.string(forType: .string) == stagedText
    }

    private func finishRecord(_ ending: ClipboardPasteRecord.Ending) {
        guard let record = pendingRecord else { return }
        pendingRecord = nil
        emit(record.line(ending))
    }

    private func emit(_ line: String) {
        Self.log.info("\(line, privacy: .public)")
        onLog?(line)
    }
}
