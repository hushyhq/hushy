#!/usr/bin/env python3
"""Embed every Sources/MurmurCore/Lexicon/Packs/*.json into DomainPackData.swift (the binary carries the packs;
nothing is read from disk at run time). Run after build_nba_pack.py or any pack edit:

    python3 -I scripts/lexicon/embed_packs.py
"""
import glob, json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../Sources/MurmurCore/Lexicon")
paths = sorted(glob.glob(os.path.join(root, "Packs", "*.json")))
lines = ["// Generated by scripts/lexicon/embed_packs.py from Lexicon/Packs/*.json. Do not edit by hand.",
         "", "enum DomainPackData {", "    /// File name and JSON of each bundled pack, in file-name order.", "    static let files: [(name: String, json: String)] = ["]
for path in paths:
    text = open(path, encoding="utf-8").read()
    json.loads(text)
    assert '"""#' not in text
    lines.append('        ("%s", #"""' % os.path.basename(path))
    lines.append(text.rstrip("\n"))
    lines.append('"""#),')
lines += ["    ]", "", "    static var sources: [String] { files.map(\\.json) }", "}", ""]
open(os.path.join(root, "DomainPackData.swift"), "w", encoding="utf-8").write("\n".join(lines))
print(len(paths), "packs embedded")
