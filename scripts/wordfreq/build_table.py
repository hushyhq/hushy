#!/usr/bin/env python3
"""Turn the word counts of `count_words.py` into the table Hushy ships (Sources/MurmurCore/Lexicon/WordFrequencyData.swift).

    python3 -I scripts/wordfreq/build_table.py COUNTS.json [COUNTS.json ...] OUT.swift [--min-zipf 2.0] [--stats]

The grade of a word is its Zipf value (log10 of occurrences per billion words) in steps of a quarter, from 1.5 (A) to
7.75 (Z), computed from lowercase occurrences only, so a name that is almost always written with a capital ("sarah")
scores low and an ordinary word ("will", "mark") scores high. A form that appears capitalized in the middle of a
sentence more often than lowercase is a name or a title first and a word second: its score is cut by the share of its
occurrences that are capitalized (see `adjusted`). Words keep an entry only from `--min-zipf` upwards.
Entries are sorted by word; each is the word, then its grade letter, with no separator (a word has no capitals).
"""
import json, math, sys
from collections import Counter

STEP, FLOOR = 0.25, 1.5


def adjusted(lower, mid):
    """Occurrences that count towards 'a word people write in lowercase'."""
    if lower <= 0:
        return 0.0
    share_cap = mid / (mid + lower)
    return lower * (1.0 - share_cap) ** 2 if share_cap > 0.5 else lower


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    min_zipf = float(argv[argv.index("--min-zipf") + 1]) if "--min-zipf" in argv else 2.0
    if "--min-zipf" in argv:
        args.remove(argv[argv.index("--min-zipf") + 1])
    out_path = args[-1]
    lower, mid, total = Counter(), Counter(), 0
    for path in args[:-1]:
        data = json.load(open(path))
        lower.update(data["lower"]); mid.update(data["mid"]); total += data["total"]
    entries = []
    for word, n in lower.items():
        if len(word) > 24 or len(word) < 1 or word.strip("'") != word:
            continue
        score = adjusted(n, mid.get(word, 0))
        if score <= 0:
            continue
        zipf = math.log10(score / total * 1e9)
        if zipf < min_zipf:
            continue
        grade = max(0, min(25, round((zipf - FLOOR) / STEP)))
        entries.append((word, grade))
    entries.sort(key=lambda e: e[0].encode())
    blob = "".join(w + chr(ord("A") + g) for w, g in entries)
    assert blob.isascii() and all(c.islower() or c == "'" or c.isupper() for c in blob)
    with open(out_path, "w") as out:
        out.write("// Generated by scripts/wordfreq/build_table.py from C4 word counts (see docs/engineering/WORD-FREQUENCY.md). Do not edit.\n")
        out.write("// Entries sorted by word; each is the word then one grade letter A...Z (Zipf 1.5 + 0.25 per step). One line on purpose.\n")
        out.write("enum WordFrequencyData {\n")
        out.write(f"    static let entryCount = {len(entries)}\n")
        out.write(f"    static let table: StaticString = \"{blob}\"\n")
        out.write("}\n")
    print(f"{len(entries)} entries, {len(blob)} bytes, tokens {total}", file=sys.stderr)
    if "--stats" in argv:
        for lo in [2.0, 2.5, 3.0, 3.5, 4.0, 5.0]:
            print(f"zipf >= {lo}: {sum(1 for _, g in entries if FLOOR + g * STEP >= lo)}", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1:])
